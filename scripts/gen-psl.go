//go:build ignore

// Writes frontend/src/lib/psl.js, the Public Suffix List the frontend uses to
// print a link's registrable domain beside it, and the Go/JS agreement vectors
// its test reads.
//
// The list is NOT downloaded. It is decoded from the copy already embedded in
// the golang.org/x/net/publicsuffix this module builds against, so the domain
// the sender's core checks a card title against (publicsuffix.EffectiveTLDPlusOne)
// and the domain every reader prints are computed from the same list. Bumping
// x/net and re-running this keeps them together:
//
//	go run scripts/gen-psl.go
//
// Only what the default rule cannot express is emitted: every rule of two or
// more labels, every wildcard and every exception. A single-label rule ("com")
// says the same thing as the default "*" rule, so it is left out of the rule
// set; the TLDs are emitted separately because "does this look like a domain?"
// needs to know that "js" is not one.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/net/publicsuffix"
)

const (
	nodesBitsChildren   = 10
	nodesBitsICANN      = 1
	nodesBitsTextOffset = 16
	nodesBitsTextLength = 6

	childrenBitsWildcard = 1
	childrenBitsNodeType = 2
	childrenBitsHi       = 14
	childrenBitsLo       = 14

	nodeTypeNormal    = 0
	nodeTypeException = 1
)

var nodes, children, text string

func node(i uint32) uint64 {
	b := nodes[i*5:]
	return uint64(b[4]) | uint64(b[3])<<8 | uint64(b[2])<<16 | uint64(b[1])<<24 | uint64(b[0])<<32
}

func child(i uint32) uint32 {
	b := children[i*4:]
	return uint32(b[3]) | uint32(b[2])<<8 | uint32(b[1])<<16 | uint32(b[0])<<24
}

func label(i uint32) string {
	x := node(i)
	n := x & (1<<nodesBitsTextLength - 1)
	x >>= nodesBitsTextLength
	off := x & (1<<nodesBitsTextOffset - 1)
	return text[off : off+n]
}

// walk emits the rules under node i, whose own name (without its label) is
// parent.
func walk(i uint32, parent string, rules map[string]bool) {
	name := label(i)
	if parent != "" {
		name += "." + parent
	}
	u := uint32(node(i) >> (nodesBitsTextOffset + nodesBitsTextLength))
	u >>= nodesBitsICANN
	u = child(u & (1<<nodesBitsChildren - 1))
	lo := u & (1<<childrenBitsLo - 1)
	u >>= childrenBitsLo
	hi := u & (1<<childrenBitsHi - 1)
	u >>= childrenBitsHi
	typ := u & (1<<childrenBitsNodeType - 1)
	u >>= childrenBitsNodeType
	wildcard := u&(1<<childrenBitsWildcard-1) != 0

	multi := strings.Contains(name, ".")
	switch typ {
	case nodeTypeNormal:
		if multi {
			rules[name] = true
		}
	case nodeTypeException:
		rules["!"+name] = true
	}
	if wildcard {
		rules["*."+name] = true
	}
	for c := lo; c < hi; c++ {
		walk(c, name, rules)
	}
}

func main() {
	dir := ""
	if len(os.Args) > 1 {
		dir = os.Args[1]
	} else {
		out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/net").Output()
		if err != nil {
			fmt.Fprintln(os.Stderr, "gen-psl: go list golang.org/x/net:", err)
			os.Exit(1)
		}
		dir = strings.TrimSpace(string(out))
	}
	ps := filepath.Join(dir, "publicsuffix")
	read := func(name string) string {
		b, err := os.ReadFile(filepath.Join(ps, name))
		if err != nil {
			fmt.Fprintln(os.Stderr, "gen-psl:", err)
			os.Exit(1)
		}
		return string(b)
	}
	nodes, children, text = read("data/nodes"), read("data/children"), read("data/text")
	table := read("table.go")
	version := regexp.MustCompile(`const version = "([^"]*)"`).FindStringSubmatch(table)
	numTLD := regexp.MustCompile(`const numTLD = (\d+)`).FindStringSubmatch(table)
	if version == nil || numTLD == nil {
		fmt.Fprintln(os.Stderr, "gen-psl: table.go has changed shape; update this generator")
		os.Exit(1)
	}
	n, _ := strconv.Atoi(numTLD[1])

	rules := map[string]bool{}
	var tlds []string
	for i := uint32(0); i < uint32(n); i++ {
		tlds = append(tlds, label(i))
		walk(i, "", rules)
	}
	list := make([]string, 0, len(rules))
	for r := range rules {
		list = append(list, r)
	}
	sort.Strings(list)
	sort.Strings(tlds)

	var b strings.Builder
	b.WriteString("// GENERATED by scripts/gen-psl.go from golang.org/x/net/publicsuffix. DO NOT EDIT.\n")
	b.WriteString("// Source: " + version[1] + "\n")
	b.WriteString("// Licence of the list: MPL-2.0 (https://publicsuffix.org/).\n")
	b.WriteString("//\n// RULES holds every rule the default \"*\" rule cannot express (two or more\n")
	b.WriteString("// labels, wildcards, exceptions), as \"parent:first,first;…\"; TLDS every\n")
	b.WriteString("// top-level label the list knows. Decoded in lib/regdomain.js.\n")
	fmt.Fprintf(&b, "export const PSL_VERSION = %q;\n", version[1])
	fmt.Fprintf(&b, "export const TLDS = %q;\n", strings.Join(tlds, " "))
	// Grouped by everything after the rule's first label, which is where nearly
	// all the repetition is ("co.uk ac.uk gov.uk …" becomes "uk:co,ac,gov").
	// Format: "parent:first,first;parent:…", a leading "!" kept on the first
	// label of an exception.
	groups := map[string][]string{}
	for _, r := range list {
		bang := strings.HasPrefix(r, "!")
		body := strings.TrimPrefix(r, "!")
		first, parent, _ := strings.Cut(body, ".")
		if bang {
			first = "!" + first
		}
		groups[parent] = append(groups[parent], first)
	}
	parents := make([]string, 0, len(groups))
	for p := range groups {
		parents = append(parents, p)
	}
	sort.Strings(parents)
	var gs []string
	for _, p := range parents {
		gs = append(gs, p+":"+strings.Join(groups[p], ","))
	}
	fmt.Fprintf(&b, "export const RULES = %q;\n", strings.Join(gs, ";"))
	if err := os.WriteFile("frontend/src/lib/psl.js", []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen-psl:", err)
		os.Exit(1)
	}

	// Agreement vectors: what Go says, for the JS test to match.
	hosts := []string{
		"youtube.com", "www.youtube.com", "m.youtube.com", "youtu.be",
		"youtube.com.evil.example", "evil.example", "a.b.evil.example",
		"bbc.co.uk", "www.bbc.co.uk", "co.uk", "foo.github.io", "github.io",
		"www.ck", "foo.www.ck", "a.b.ck", "foo.blogspot.com", "s3.amazonaws.com",
		"bucket.s3.amazonaws.com", "example.com.au", "x.y.example.com.au",
		"xn--yutube-wqf.com", "www.xn--yutube-wqf.com", "paypal.com.xn--80ak6aa92e.com",
		"kyoto.jp", "city.kyoto.jp", "foo.city.kyoto.jp", "unknowntld", "a.unknowntld",
		"b.a.unknowntld", "vimeo.com", "player.vimeo.com", "localhost",
	}
	vec := map[string]string{}
	for _, h := range hosts {
		d, err := publicsuffix.EffectiveTLDPlusOne(h)
		if err != nil {
			d = ""
		}
		vec[h] = d
	}
	vj, _ := json.MarshalIndent(map[string]any{"version": version[1], "etld1": vec}, "", "  ")
	if err := os.WriteFile("frontend/src/lib/regdomain.vectors.json", append(vj, '\n'), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen-psl:", err)
		os.Exit(1)
	}
	fmt.Printf("gen-psl: %d rules, %d TLDs (%s)\n", len(list), len(tlds), version[1])
}
